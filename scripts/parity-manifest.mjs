#!/usr/bin/env node
// Golden-fixture manifest and parity-matrix ownership/test columns.
//
//   node scripts/parity-manifest.mjs --write   regenerate both from the tree
//   node scripts/parity-manifest.mjs --check   fail if anything is stale/missing
//
// Inputs: native/run-*-tests.sh (Swift test dirs and fixture paths are parsed
// from them), scripts/parity-map.json (curated: matrix row -> owning roadmap
// phase, Swift runners, React Native oracle tests), and __fixtures__/.
// Outputs: docs/native-fixture-manifest.json and the "Owner" and "Automated
// tests" columns of docs/native-parity-matrix.md.
//
// The manifest hashes files; it does not record pass/fail. Fixture hashes are
// the recorded inputs/golden outputs, so a fixture edit shows up as a diff.

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = join(ROOT, 'docs/native-fixture-manifest.json');
const MATRIX = join(ROOT, 'docs/native-parity-matrix.md');
const MAP = JSON.parse(readFileSync(join(ROOT, 'scripts/parity-map.json'), 'utf8'));
const mode = process.argv[2];
if (mode !== '--write' && mode !== '--check') {
  console.error('usage: parity-manifest.mjs --write | --check');
  process.exit(2);
}

const sha = (buf) => createHash('sha256').update(buf).digest('hex');
const fileHash = (p) => sha(readFileSync(join(ROOT, p)));
const walk = (dir) =>
  readdirSync(join(ROOT, dir), { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]);
const dirHash = (dir) =>
  sha(walk(dir).sort().map((f) => `${f}\0${fileHash(f)}`).join('\n'));

const problems = [];

// ---- Swift runners ---------------------------------------------------------
const runners = {};
for (const f of readdirSync(join(ROOT, 'native')).filter((n) => /^run-.*-tests\.sh$/.test(n)).sort()) {
  const name = f.replace(/^run-/, '').replace(/-tests\.sh$/, '');
  if (name === 'all-domain') continue;
  const src = readFileSync(join(ROOT, 'native', f), 'utf8');
  const dirs = [...new Set([...src.matchAll(/native\/([A-Za-z0-9]+Tests)\//g)].map((m) => `native/${m[1]}`))]
    .filter((d) => existsSync(join(ROOT, d)));
  const fixtureRefs = [...new Set([...src.matchAll(/native\/[A-Za-z0-9]+Tests\/Fixtures[A-Za-z0-9/._-]*/g)].map((m) => m[0]))];
  const fixtures = fixtureRefs
    .flatMap((p) => (existsSync(join(ROOT, p)) ? (statSync(join(ROOT, p)).isDirectory() ? walk(p) : [p]) : []))
    .sort()
    .map((p) => ({ path: p, sha256: fileHash(p), bytes: statSync(join(ROOT, p)).size }));
  runners[name] = {
    script: `native/${f}`,
    scriptSha256: fileHash(`native/${f}`),
    testSources: dirs.map((d) => ({ path: d, sha256: dirHash(d) })),
    fixtures,
  };
}

// ---- React Native oracles --------------------------------------------------
const rnTests = {};
for (const f of readdirSync(join(ROOT, '__tests__')).filter((n) => /\.test\.[jt]sx?$/.test(n))) {
  rnTests[f.replace(/\.test\.[jt]sx?$/, '')] = `__tests__/${f}`;
}
const oracles = Object.fromEntries(Object.entries(rnTests).sort().map(([k, p]) => [
  k, { path: p, sha256: fileHash(p) }]));
const rnFixtures = walk('__fixtures__').sort().map((p) => ({
  path: p,
  sha256: fileHash(p),
  usedBy: Object.entries(rnTests)
    .filter(([, tp]) => readFileSync(join(ROOT, tp), 'utf8').includes(p.split('/').pop().replace(/\.[jt]s$/, '')))
    .map(([k]) => k),
}));

// ---- curated map validation ------------------------------------------------
for (const [row, e] of Object.entries(MAP)) {
  for (const r of e.runners) if (!runners[r]) problems.push(`map "${row}": no runner run-${r}-tests.sh`);
  for (const o of e.oracles) if (!oracles[o]) problems.push(`map "${row}": no RN test __tests__/${o}.test.*`);
}

const manifest = {
  note: 'Generated by scripts/parity-manifest.mjs. Hashes only; no pass/fail. Regenerate with --write.',
  swiftRunners: runners,
  reactNativeOracles: oracles,
  reactNativeFixtures: rnFixtures,
  matrixRows: MAP,
};
const manifestText = `${JSON.stringify(manifest, null, 1)}\n`;

// ---- matrix columns --------------------------------------------------------
const lines = readFileSync(MATRIX, 'utf8').split('\n');
let section = '';
const seen = new Set();
const cellOwner = (e) => (e.phase == null ? 'Unassigned' : `Phase ${e.phase}`);
const cellTests = (e) => {
  const parts = [];
  if (e.runners.length) parts.push(`Swift: ${e.runners.join(', ')}`);
  if (e.oracles.length) parts.push(`RN: ${e.oracles.join(', ')}`);
  return parts.length ? parts.join(' · ') : 'none recorded';
};
const splitRow = (l) => l.slice(1, l.lastIndexOf('|')).split(/(?<!\\)\|/).map((c) => c.trim());
const out = lines.map((line) => {
  if (line.startsWith('## ')) section = line.slice(3).trim();
  if (!line.startsWith('|')) return line;
  const cells = splitRow(line);
  if (cells[0] === 'React Native surface' || cells[0] === 'Capability') {
    return `| ${cells.slice(0, 3).join(' | ')} | Owner | Automated tests |`;
  }
  if (/^-+$/.test(cells[0].replace(/:/g, ''))) return '|---|---|---|---|---|';
  const key = MAP[`${section}/${cells[0]}`] ? `${section}/${cells[0]}` : cells[0];
  const e = MAP[key];
  if (!e) {
    problems.push(`matrix row "${section}/${cells[0]}" has no entry in scripts/parity-map.json`);
    return line;
  }
  seen.add(key);
  return `| ${cells.slice(0, 3).join(' | ')} | ${cellOwner(e)} | ${cellTests(e)} |`;
});
for (const k of Object.keys(MAP)) if (!seen.has(k)) problems.push(`map entry "${k}" matches no matrix row`);
const matrixText = out.join('\n');

if (mode === '--write') {
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  writeFileSync(MANIFEST, manifestText);
  writeFileSync(MATRIX, matrixText);
  console.log(`wrote ${relative(ROOT, MANIFEST)} (${Object.keys(runners).length} runners, ${Object.keys(oracles).length} RN oracles) and matrix columns`);
} else {
  if (!existsSync(MANIFEST) || readFileSync(MANIFEST, 'utf8') !== manifestText) problems.push('docs/native-fixture-manifest.json is stale: run --write');
  if (readFileSync(MATRIX, 'utf8') !== matrixText) problems.push('docs/native-parity-matrix.md Owner/Automated tests columns are stale: run --write');
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  console.log('fixture manifest and matrix columns are current');
}
